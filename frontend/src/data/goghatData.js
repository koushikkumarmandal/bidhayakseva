// Helper to get villages for a chosen Panchayat
export const getVillagesByPanchayat = (panchayatName) => {
  if (!panchayatName) return GOGHAT_VILLAGES;
  
  // Exact match
  if (GOGHAT_PANCHAYAT_VILLAGES[panchayatName]) {
    return GOGHAT_PANCHAYAT_VILLAGES[panchayatName];
  }
  
  // Normalized match
  const cleanName = panchayatName.replace(/Gram Panchayat|GP/gi, '').trim().toLowerCase();
  for (const [gp, vList] of Object.entries(GOGHAT_PANCHAYAT_VILLAGES)) {
    const cleanGp = gp.replace(/Gram Panchayat|GP/gi, '').trim().toLowerCase();
    if (cleanName.includes(cleanGp) || cleanGp.includes(cleanName)) {
      return vList;
    }
  }
  
  return GOGHAT_VILLAGES;
};
